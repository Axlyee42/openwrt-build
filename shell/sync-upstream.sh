#!/usr/bin/env bash

set -euo pipefail


# ==============================================================
# OpenWrt upstream configuration
# ==============================================================

OPENWRT_REPO="https://github.com/openwrt/openwrt.git"

STATE_FILE="openwrt-version"


echo
echo "=========================================="
echo "OpenWrt 25.12 upstream check"
echo "=========================================="


# ==============================================================
# 获取最新 OpenWrt 25.12.x
# ==============================================================

LATEST="$(
    git ls-remote \
        --tags \
        "${OPENWRT_REPO}" \
        'refs/tags/v25.12.*' |
    sed 's#.*refs/tags/v##' |
    grep -E '^25\.12\.[0-9]+$' |
    sort -V |
    tail -1
)


# ==============================================================
# 检查是否成功获取版本
# ==============================================================

if [ -z "${LATEST}" ]; then

    echo
    echo "ERROR:"
    echo "Cannot find OpenWrt 25.12.x release."

    exit 1

fi


echo
echo "Latest OpenWrt:"
echo "${LATEST}"


# ==============================================================
# 读取当前版本
# ==============================================================

CURRENT=""

if [ -f "${STATE_FILE}" ]; then

    CURRENT="$(
        tr -d '[:space:]' < "${STATE_FILE}"
    )"

fi


echo
echo "Current OpenWrt:"
echo "${CURRENT:-none}"


# ==============================================================
# 比较版本
# ==============================================================

if [ "${LATEST}" = "${CURRENT}" ]; then

    echo
    echo "=========================================="
    echo "No update."
    echo "=========================================="

    exit 0

fi


# ==============================================================
# 检测到新版本
# ==============================================================

echo
echo "=========================================="
echo "OpenWrt update detected"
echo "=========================================="


echo
echo "Old:"
echo "${CURRENT:-none}"


echo
echo "New:"
echo "${LATEST}"


# ==============================================================
# 更新版本文件
# ==============================================================

printf '%s\n' "${LATEST}" > "${STATE_FILE}"


echo
echo "Version file updated:"
echo "${STATE_FILE}"


echo
echo "=========================================="
echo "Update complete"
echo "=========================================="


exit 0
